def apply_patch(files: dict[str, str], patch: dict[str, Any]
                ) -> dict[str, str]:
    """The demo files after the change of an experiment (the browser does
    the same, see web/js/lesson.js)."""
    out = dict(files)
    name = patch.get("file", "main.py")
    if patch.get("find"):
        text = out[name].replace(patch["find"], patch["replace"])
        for old, new in patch.get("also", []):
            text = text.replace(old, new)
        out[name] = text
    if patch.get("append"):
        out[name] = out[name].rstrip("\n") + "\n" + patch["append"]
    return out
