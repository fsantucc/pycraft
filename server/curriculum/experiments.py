"""The guided experiments of every level (step « Essais »).

Each experiment says, for a beginner who never programmed:

* ``do``      — exactly what to change (file, line, text);
* ``predict`` — the question to answer BEFORE running (active learning);
* ``see``     — what the console and the world show after running;
* ``why``     — the programming idea it demonstrates.

``patch`` lets the game make the change for the player (« Faire la
modification pour moi ») — a find / replace in one file of the demo, or new
program inputs / arguments. ``expect`` is never sent to the browser: the
tests run every patched demo in the sandbox and check that ``see`` tells
the truth (error type, lines present or absent, counts…).
"""
from __future__ import annotations

from typing import Any


def exp(do: str, predict: str, see: str, why: str, *, file: str = "main.py",
        find: str = "", replace: str = "", stdin: list[str] | None = None,
        argv: list[str] | None = None, entry: str = "",
        expect: dict[str, Any] | None = None) -> dict[str, Any]:
    patch: dict[str, Any] = {}
    if find:
        patch.update(file=file, find=find, replace=replace)
    if stdin is not None:
        patch["stdin"] = stdin
    if argv is not None:
        patch["argv"] = argv
    if entry:
        patch["entry"] = entry
    data: dict[str, Any] = {"do": do, "predict": predict, "see": see,
                            "why": why}
    if patch:
        data["patch"] = patch
    if expect is not None:
        data["expect"] = expect
    return data


